"""Turns the HUD's status and buff icons into Source/StatusPictures.dk.

Each image (made with the pixel-art skill, see the skill's game-asset notes) is
cut out from its plain background, cropped to the icon, scaled to SIZE x SIZE
pixels and reduced to a few colors. The UI shader draws the one-pixel outline
around it, so the picture carries only its colors and the atlas keeps a clear
one-pixel margin around each icon.

    python Tools/StatusArt/convert.py              write Source/StatusPictures.dk
    python Tools/StatusArt/convert.py --preview p  also save an enlarged preview PNG
"""
import argparse
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
SIZE = 9
COLORS = 5
BACKGROUND = 40     # how far a pixel may stray from the corner color and still be background
# Each icon and its image. The statuses come first, in the order of
# HellfeatherStatus; buffs follow.
ICONS = [
    ('Burn', 'Assets/StatusArt/Burn.png'),
    ('Chill', 'Assets/StatusArt/Chill.png'),
    ('Shock', 'Assets/StatusArt/Shock.png'),
    ('WarCry', 'Assets/StatusArt/WarCry.png'),
]
CODES = 'abcdefgh'


def cut_out(image):
    rgb = image.convert('RGB')
    corner = rgb.getpixel((0, 0))
    out = Image.new('RGBA', rgb.size)
    for y in range(rgb.height):
        for x in range(rgb.width):
            p = rgb.getpixel((x, y))
            far = sum(abs(p[i] - corner[i]) for i in range(3))
            out.putpixel((x, y), (*p, 255 if far > BACKGROUND else 0))
    return out


def icon(path):
    image = cut_out(Image.open(path))
    image = image.crop(image.getbbox())
    side = max(image.width, image.height)
    square = Image.new('RGBA', (side, side))
    square.paste(image, ((side - image.width) // 2, (side - image.height) // 2))
    small = square.resize((SIZE, SIZE), Image.BOX)
    opaque = [(x, y) for y in range(SIZE) for x in range(SIZE) if small.getpixel((x, y))[3] >= 110]
    strip = Image.new('RGB', (len(opaque), 1))
    for i, (x, y) in enumerate(opaque):
        strip.putpixel((i, 0), small.getpixel((x, y))[:3])
    quantized = strip.quantize(COLORS, method=Image.Quantize.MEDIANCUT)
    palette = quantized.getpalette()[:COLORS * 3]
    rows = [['.'] * SIZE for _ in range(SIZE)]
    for i, (x, y) in enumerate(opaque):
        rows[y][x] = CODES[quantized.getpixel((i, 0))]
    colors = [tuple(palette[i * 3:i * 3 + 3]) for i in range(COLORS)]
    return [''.join(r) for r in rows], colors


def local(name):
    return name[0].lower() + name[1:]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--preview')
    args = parser.parse_args()
    names = [name for name, _ in ICONS]
    lines = [
        '// Generated by Tools/StatusArt/convert.py. Do not edit by hand: change the',
        '// images or the converter\'s list and run it again.',
        '',
        '// The icons of her statuses and buffs. The statuses\' come first, in the',
        '// order of HellfeatherStatus.',
        'HellfeatherStatusIcon : int',
        '#@{',
        ',\n'.join('    ' + name for name in names),
        '}',
        '',
        'HellfeatherStatusArt',
        '#{',
        f'    #int Size = {SIZE}',
        '',
        '    // Paints each icon into the atlas at IconX, IconY, inside a clear',
        '    // one-pixel margin for the outline the UI shader draws.',
        '    Paint(QuaxelUi& ui)',
        '    {',
    ]
    pictures = {}
    for name, path in ICONS:
        rows, colors = icon(ROOT / path)
        pictures[name] = (rows, colors)
        lines.append(f'        HellfeatherStatusIcon {local(name)} = HellfeatherStatusIcon.{name}')
        for r, text in enumerate(rows):
            lines.append(f'        Row(ui, {local(name)}, {r}, "{text}")')
    lines += [
        '    }',
        '',
        '    -Row(QuaxelUi& ui, HellfeatherStatusIcon icon, int row, string text)',
        '    {',
        '        for column : 0; column < Size; column++ {',
        '            int code = (int)CodeUnitAt(text, (long)column)',
        '            if code == 46 { continue }',
        '            HellfeatherInventoryArt.Put(ui, HellfeatherStatusArt.IconX(icon) + 1 + column, HellfeatherStatusArt.IconY + 1 + row, ColorOf(icon, code))',
        '        }',
        '    }',
        '',
        '    // A picture letter\'s color, a for the first.',
        '    int ColorOf(HellfeatherStatusIcon icon, int code)',
        '    {',
    ]
    for name in names:
        _, colors = pictures[name]
        for i, c in enumerate(colors):
            lines.append(f'        if icon == HellfeatherStatusIcon.{name} && code == {ord(CODES[i])} {{ return 0x{c[0]:02x}{c[1]:02x}{c[2]:02x} }}')
    lines += ['        return 0', '    }', '}', '']
    (ROOT / 'Source/StatusPictures.dk').write_text('\n'.join(lines), encoding='utf-8')
    print('wrote Source/StatusPictures.dk')
    if args.preview:
        scale = 16
        sheet = Image.new('RGB', ((SIZE + 2) * scale * len(names), (SIZE + 2) * scale), (40, 36, 32))
        for n, name in enumerate(names):
            rows, colors = pictures[name]
            for y, text in enumerate(rows):
                for x, ch in enumerate(text):
                    if ch == '.':
                        continue
                    c = colors[CODES.index(ch)]
                    for dy in range(scale):
                        for dx in range(scale):
                            sheet.putpixel(((n * (SIZE + 2) + 1 + x) * scale + dx, (1 + y) * scale + dy), c)
        sheet.save(args.preview)


if __name__ == '__main__':
    main()
