"""Turns the quest log's reference images in Assets/QuestArt into Source/QuestPictures.dk.

Quest icons are converted like item icons (see Tools/ItemArt/convert.py): cut out
from the background, scaled into a 32-pixel square less a one-pixel margin for the
shader's outline, each cell mapped to the nearest color the icon may use.

The niche is stretched to fill its whole slot with no margin, since it is painted
straight onto the panel's stone. Its opening comes out empty or dark; either way
it is filled with the darkest color, so every icon sits in a deep recess.

    python Tools/QuestArt/convert.py              write Source/QuestPictures.dk
    python Tools/QuestArt/convert.py --preview p  also save a preview PNG
"""
import argparse
import importlib.util
import json
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
spec = importlib.util.spec_from_file_location('itemart', HERE.parent / 'ItemArt' / 'convert.py')
itemart = importlib.util.module_from_spec(spec)
spec.loader.exec_module(itemart)

ICON = 32          # pixels across a quest icon, margin included
NICHE = 48         # pixels across a niche
RECESS = 'X'       # what the niche's opening is filled with: dark stone, not black, so dark icons still show


def fill_opening(rows):
    """Empty cells between a row's outermost solid cells become the recess."""
    out = []
    for row in rows:
        solid = [i for i, c in enumerate(row) if c != '.']
        if not solid:
            out.append(row)
            continue
        left, right = solid[0], solid[-1]
        out.append(row[:left] + row[left:right + 1].replace('.', RECESS) + row[right + 1:])
    return out


def write_duck(icons, niche, path):
    out = [
        '// Generated by Tools/QuestArt/convert.py from Assets/QuestArt. Do not edit by hand:',
        '// change the images or Tools/QuestArt/quests.json and run the converter again.',
        'HellfeatherQuestPictures',
        '#{',
        '    // Act I in order, from The Dead Woman\'s Reason to The Millrace Door.',
        '    Draw(int quest, HellfeatherItemPicture& p)',
        '    {',
    ]
    for i, name in enumerate(icons):
        keyword = 'if' if i == 0 else 'else if'
        out.append(f'        {keyword} quest == {i} {{ Picture{name}(p) }}')
    out.append('    }')
    out.append('')
    out.append('    Niche(HellfeatherItemPicture& p)')
    out.append('    {')
    for i, row in enumerate(niche):
        if row.strip('.'):
            out.append(f'        p.Row({i}, "{row}")')
    out.append('    }')
    for name, rows in icons.items():
        out.append('')
        out.append(f'    -Picture{name}(HellfeatherItemPicture& p)')
        out.append('    {')
        for i, row in enumerate(rows):
            # Every row is written, so a picture is always its full height.
            out.append(f'        p.Row({i}, "{row}")')
        out.append('    }')
    out.append('}')
    path.write_text('\n'.join(out) + '\n', encoding='utf-8', newline='\r\n')


def save_preview(icons, niche, colors, path, zoom=4):
    """Each icon in its niche, over stone grey, with the shader's outline."""
    count = len(icons)
    sheet = Image.new('RGB', (count * (NICHE + 4) * zoom, (NICHE + 4) * zoom), (60, 56, 50))

    def put(bx, by, x, y, color):
        for yy in range(zoom):
            for xx in range(zoom):
                sheet.putpixel(((bx + x) * zoom + xx, (by + y) * zoom + yy), color)

    for index, rows in enumerate(icons.values()):
        bx, by = index * (NICHE + 4) + 2, 2
        for y, row in enumerate(niche):
            for x, code in enumerate(row):
                if code != '.':
                    put(bx, by, x, y, colors[code])
        ox, oy = (NICHE - ICON) // 2, NICHE - ICON - 4

        def solid(x, y):
            return 0 <= x < ICON and 0 <= y < ICON and rows[y][x] != '.'

        for y in range(ICON):
            for x in range(ICON):
                if solid(x, y):
                    put(bx + ox, by + oy, x, y, colors[rows[y][x]])
                elif any(solid(x + dx, y + dy) for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))):
                    put(bx + ox, by + oy, x, y, (21, 17, 14))
    sheet.save(path)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--preview', help='also save a preview PNG here')
    args = parser.parse_args()
    config = json.loads((HERE / 'quests.json').read_text(encoding='utf-8'))
    colors = itemart.palette()

    def picture(name, entry, width, height):
        image = Image.open(ROOT / 'Assets/QuestArt' / f'{name}.png').convert('RGB')
        codes = [c for c in entry.get('colors', ''.join(colors)) if c in colors]
        return itemart.convert(image, width, height, colors, codes, entry.get('shadow', True), entry.get('fill', False))

    inner = ICON - 2 * itemart.MARGIN
    pad = '.' * itemart.MARGIN
    icons = {}
    for name, entry in config['quests'].items():
        rows = picture(name, entry, inner, inner)
        icons[name] = [pad * ICON] * itemart.MARGIN + [pad + r + pad for r in rows] + [pad * ICON] * itemart.MARGIN
    niche = fill_opening(picture('Niche', config['parts']['Niche'], NICHE, NICHE))
    write_duck(icons, niche, ROOT / 'Source/QuestPictures.dk')
    if args.preview:
        save_preview(icons, niche, colors, args.preview)


if __name__ == '__main__':
    main()
